/** Dots, spaces and punctuation are ignored in abbreviation searches. */
export function degreeSearchToken(value: string): string {
  return value.toLocaleLowerCase().replace(/[^a-z0-9]+/g, '')
}

const oldAwardNames: Record<string, string> = {
  'btech': 'Bachelor of Technology',
  'be': 'Bachelor of Engineering',
  'bsc': 'Bachelor of Science',
  'bca': 'Bachelor of Computer Applications',
  'bcom': 'Bachelor of Commerce',
  'bba': 'Bachelor of Business Administration',
  'ba': 'Bachelor of Arts',
  'mtech': 'Master of Technology',
  'msc': 'Master of Science',
}

/** Recognize the old profile selector's nine historical values without
 * confusing ambiguous abbreviated awards such as MCA, MPA, or MHA.
 */
export function canonicalCurrentDegree(value: string): string | null {
  const exact = CURRENT_DEGREE_TITLES.find((item) => item.title === value)
  if (exact) return exact.title
  return oldAwardNames[degreeSearchToken(value)] ?? null
}

export function isCurrentDegreeTitle(value: string): boolean {
  return CURRENT_DEGREE_TITLES.some((item) => item.title === value)
}
